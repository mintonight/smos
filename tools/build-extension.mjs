#!/usr/bin/env node
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outDir = path.join(root, 'extension', 'content')

export const PLATFORMS = [
  { key: 'bilibili', source: 'smos-bilibili/smos-bilibili.user.js', output: '10-bilibili.js' },
  { key: 'douyin', source: 'smos-douyin/smos-douyin.user.js', output: '20-douyin.js' },
  { key: 'zhihu', source: 'smos-zhihu/smos-zhihu.user.js', output: '30-zhihu.js' },
  { key: 'xiaohongshu', source: 'smos-xiaohongshu/smos-xiaohongshu.user.js', output: '40-xiaohongshu.js' },
]

const startMarker = ';(() => {'
const endMarker = '})()'

function wrap(sourcePath, text) {
  const start = text.indexOf(startMarker)
  const end = text.lastIndexOf(endMarker)
  if (start < 0 || end <= start) {
    throw new Error(`Cannot locate the IIFE in ${sourcePath}`)
  }
  let body = text.slice(start + startMarker.length, end)
  body = body.replace(/^\s*'use strict'\s*\n/, '')
  const version = (text.match(/@version\s+(\S+)/) || [])[1] || '0.0.0'
  return `/* Generated by tools/build-extension.mjs from ${sourcePath} (v${version}). Do not edit directly. */
;(() => {
  'use strict'
  const boot = () => {${body}
  }
  window.__SMOS_EXT__.ready.then(boot).catch((error) => {
    console.error('[SMOS] ${path.basename(sourcePath)} boot failed', error)
  })
})()
`
}

export async function build({ check = false } = {}) {
  await mkdir(outDir, { recursive: true })
  const results = []
  for (const platform of PLATFORMS) {
    const sourcePath = platform.source.replaceAll('\\', '/')
    const text = await readFile(path.join(root, platform.source), 'utf8')
    const content = wrap(sourcePath, text)
    const target = path.join(outDir, platform.output)
    if (check) {
      let existing = ''
      try {
        existing = await readFile(target, 'utf8')
      } catch {
        // missing file is reported below
      }
      if (existing !== content) {
        throw new Error(`${platform.output} is out of date; run node tools/build-extension.mjs`)
      }
    } else {
      await writeFile(target, content, 'utf8')
    }
    results.push({ ...platform, target })
  }
  return results
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const results = await build({ check })
  console.log(`${check ? 'Verified' : 'Generated'} ${results.length} extension content scripts.`)
}
